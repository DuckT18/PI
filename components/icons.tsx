// Helper to get device-type icon
export function getDeviceIcon(type: string, size = 22, className?: string) {
  switch (type) {
    case "light": return <LightIcon size={size} className={className} />;
    case "ac": return <AcIcon size={size} className={className} />;
    case "tv": return <TvIcon size={size} className={className} />;
    case "speaker": return <SpeakerIcon size={size} className={className} />;
    case "camera": return <CameraIcon size={size} className={className} />;
    case "lock": return <LockIcon size={size} className={className} />;
    case "sensor": return <SensorIcon size={size} className={className} />;
    case "plug": return <PlugIcon size={size} className={className} />;
    case "fan": return <FanIcon size={size} className={className} />;
    case "curtain": return <CurtainIcon size={size} className={className} />;
    default: return <DevicesIcon size={size} className={className} />;
  }
}
